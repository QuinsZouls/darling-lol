#!/bin/sh
# packaging/common/build-deb.sh -- the T3 `.deb` builder (PLAN 9/9.7, TASKS.md T3).
#
# Two binary packages, one staging tree (PLAN 5/D3): `darling-lol` (the runtime, amd64) and
# `darling-lol-launcher` (the per-user wrapper + templates, all). Both are built here, from the
# file lists packaging/common/stage.sh already split -- this script never re-derives what belongs
# to which package, it *subtracts* the other list from a copy of the tree.
#
#   dpkg-deb --build --root-owner-group -Zxz
#
# is the whole build (PLAN 9 preamble, 9.7, C13): no dh, no debhelper, no debian/rules, no
# dpkg-gencontrol -- the payload is already installed into a DESTDIR by cmake, so there is nothing
# to compile, and dh_shlibdeps/dh_strip/dh_fixperms would run over 33 498 files of which 142 are
# Mach-O shared objects (PLAN 22). `--root-owner-group` is what makes an unprivileged build emit
# root:root entries; `-Zxz` because zstd is unreadable on dpkg < 1.21.18 (C13).
#
# Nothing is hand-written into the package: the control file, the three maintainer scripts and the
# changelog are rendered by packaging/common/render.sh from packaging/deb/*.in, the copyright is
# generated by packaging/deb/mk-copyright.sh from the pinned upstream debian/copyright, and the
# file lists come from stage.sh. The version is derived once (pkg-version.sh) and then *asserted*
# against what the rendered control file actually says, so the artifact name cannot disagree with
# the metadata inside it.
#
# usage: build-deb.sh [fixture]
#
#   (no argument)  build from the real staging tree: $DIST/pkg/root + $DIST/pkg/{files.runtime,
#                  files.launcher,installed-size-kib}, i.e. after scripts/build-packaging.sh and
#                  packaging/common/stage.sh. Fails loudly when they are missing.
#   fixture        build from packaging/testdata/mkfixture.sh's hostile-shape tree, through the
#                  SAME code path (mkfixture.sh -> stage.sh -> render.sh -> dpkg-deb). There is no
#                  x86-64 payload on this box, so this is the only executable form of G-DEB-1..4
#                  (TASKS.md T3's gate block writes exactly these artifacts). The output names are
#                  $DIST/fix.deb and $DIST/fix-launcher.deb, as TASKS.md T3 spells them. The
#                  fixture has no pinned checkout, so the generated copyright carries a visible
#                  `Comment:` line saying the upstream stanzas were omitted; pass
#                  UPSTREAM_COPYRIGHT=FILE to exercise the real concatenation.
#
# Environment:
#   DIST                 output/staging root (default: dist; relative paths are resolved against
#                        the repository root). Fixture artifacts land here.
#   DEB_FAMILY           dependency list to render: noble|bookworm (default: noble). Also becomes
#                        render.sh --release.
#   TAG                  version tag (default: `git describe --tags --always`). Pass it explicitly
#                        in CI and in harnesses: a value inherited from the checkout is state this
#                        script does not own (TASKS rule 7/C35).
#   MAINTAINER           the address in `Maintainer:`/the changelog trailer. Default:
#                        darling-lol@users.noreply.github.com (PLAN 25 Q1).
#   FIXTURE_DIR          where `fixture` builds the staged tree (default: $DIST/fixture).
#   UPSTREAM_COPYRIGHT   pinned upstream debian/copyright to inline (default:
#                        <repo>/build/darling-src/debian/copyright).
#
# Only dpkg-deb + the usual POSIX tools are needed (PLAN 9 preamble). `fixture` additionally
# needs the packaging/testdata fixture scripts, which are `sh` (verified: `fixture` runs under
# dash).
set -eu

dir=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)   # packaging/common
repo=$(CDPATH='' cd -- "$dir/../.." && pwd)          # repository root

prog=${0##*/}
fatal() {
  echo "$prog: FATAL $*" >&2
  exit 1
}
note() {
  echo "$prog: $*"
}

mode=production
case "${1:-}" in
  "") : ;;
  fixture) mode=fixture ;;
  -h | --help) sed -n '2,46p' "$0"; exit 0 ;;
  *) fatal "unknown argument '$1' (usage: $prog [fixture])" ;;
esac
[ "$#" -le 1 ] || fatal "too many arguments (usage: $prog [fixture])"

deb_family=${DEB_FAMILY:-noble}
case "$deb_family" in
  noble | bookworm) : ;;
  *) fatal "DEB_FAMILY must be noble or bookworm (got '$deb_family'): the release selects packaging/common/deps.deb.<release>" ;;
esac
# One architecture for both packages: the runtime is amd64-only (PLAN 5/D3) and the launcher is
# Architecture: all. `arch` is only ever used in the artifact name.
arch=amd64

dist=${DIST:-dist}
case "$dist" in
  /*) : ;;
  *) dist=$repo/$dist ;;
esac
fixture_dir=${FIXTURE_DIR:-$dist/fixture}
maintainer=${MAINTAINER:-darling-lol@users.noreply.github.com}
upstream_copyright=${UPSTREAM_COPYRIGHT:-$repo/build/darling-src/debian/copyright}
# An explicit --tag is passed to render.sh in every mode: without it render.sh would fall back to
# `git describe`, i.e. to state that belongs to whatever checkout happens to be current.
tag=${TAG:-$(git describe --tags --always 2>/dev/null || echo 0.0.0)}
ver=$(sh "$dir/pkg-version.sh" --deb "$tag")

cd "$repo"
command -v dpkg-deb >/dev/null 2>&1 || fatal "dpkg-deb is not installed: this builder is dpkg-deb and nothing else (PLAN 9 preamble)"

# --- 1. The staged tree + the three file lists ------------------------------------------------
if [ "$mode" = fixture ]; then
  pkg=$fixture_dir/pkg
  root=$fixture_dir/root
  rm -rf "$fixture_dir"
  bash packaging/testdata/mkfixture.sh "$fixture_dir" >/dev/null || fatal "mkfixture.sh failed"
  sh "$dir/stage.sh" "$root" "$pkg" >/dev/null || fatal "stage.sh failed over the fixture tree"
  # TASKS.md T3's gate block names these two artifacts literally.
  runtime_deb=$dist/fix.deb
  launcher_deb=$dist/fix-launcher.deb
  copyright_missing=note
else
  pkg=$dist/pkg
  root=$pkg/root
  # Filled in at step 6, from the *rendered* control file: prod_artifacts=1 means "name the
  # artifact after the version dpkg-deb will report", never after a second derivation of it.
  runtime_deb=
  launcher_deb=
  copyright_missing=fail
fi
mkdir -p "$dist"
[ -d "$root/usr/libexec/darling" ] || fatal "$root/usr/libexec/darling is missing: run scripts/build-packaging.sh and packaging/common/stage.sh first"
for a in files.runtime files.launcher installed-size-kib; do
  [ -s "$pkg/$a" ] || fatal "$pkg/$a is missing or empty: run packaging/common/stage.sh first (it owns the split)"
done

# --- 2. render.sh wrappers ---------------------------------------------------------------------
# `render TEMPLATE [render.sh flags...]` prints the rendered file on stdout, so every call site
# looks like PLAN 9.7's `render packaging/deb/control.in dist/pkg/deb/DEBIAN/control`.
render() {
  sh "$dir/render.sh" --family deb --release "$deb_family" --tag "$tag" \
    --maintainer "$maintainer" "$@"
}

# check_no_tokens FILE -- render.sh already refuses to emit a stream containing an @TOKEN@ or an
# unsubstituted ${binary:Version} (G-STATIC-4); this re-checks the *installed* file, because an
# unsubstituted substvar is a silent, installable bug rather than a build error (PLAN 9.2).
check_no_tokens() {
  if grep -qE '@[A-Za-z_]+@|\$\{binary:Version\}' "$1"; then
    echo "$prog: FATAL $1 still contains a template token or an unexpanded \${binary:Version}:" >&2
    grep -nE '@[A-Za-z_]+@|\$\{binary:Version\}' "$1" >&2 || true
    exit 1
  fi
}

# build_tree DEST SUBTRACT_LIST OWN_LIST -- the shared half of both packages: copy the staging
# tree, subtract the paths the OTHER package owns, then drop the directories that subtraction left
# empty. stage.sh's lists are unquoted `/path` lines (step 3 for files.all, step 4 for
# files.launcher), so the leading `/` is what makes `$dest$path` work.
#
# The pruning step matters: removing the opcode's files can leave the other package's *container*
# directories behind as empty entries (measured: the runtime .deb used to claim
# ./usr/lib/darling-lol/{scripts,tools}/ because the launcher's files in them had just been
# removed). Directories may legally be shared between two packages, but a package should not claim
# a directory it empties out. A directory that is empty AND belongs to this package's own list
# (`private/tmp`, the SDK's empty dirs -- PLAN 13.2/13.3) is kept: that is the whole rule.
build_tree() {
  rm -rf "$1"
  mkdir -p "$1"
  cp -a "$root/." "$1/"
  while IFS= read -r p; do
    # `/` would mean "delete the whole tree": the T1 fix that stopped -printf emitting the
    # starting point made this impossible, and this guard keeps it that way.
    if [ -n "$p" ] && [ "$p" != / ]; then rm -rf -- "$1$p"; fi
  done < "$pkg/$2"
  # Repeat until a pass removes nothing: one pass would leave the *parent* of a pruned directory
  # behind (it was not empty when the snapshot was taken). Collected first, deleted second: never
  # walk a tree while removing from it.
  changed=1
  while [ "$changed" = 1 ]; do
    changed=0
    (cd "$1" && find . -depth -type d -empty -printf '/%P\n') > "$pkg/empty.dirs"
    while IFS= read -r d; do
      if [ -n "$d" ] && [ "$d" != / ] && ! grep -qxF "$d" "$pkg/$3"; then
        rm -rf -- "$1$d"
        changed=1
      fi
    done < "$pkg/empty.dirs"
  done
}

# --- 3. the runtime tree -----------------------------------------------------------------------
work=$pkg/deb
build_tree "$work" files.launcher files.runtime

# stage.sh step 2 asserted this on the staging tree; cp -a preserves modes, and this is the one
# bit whose loss turns every launch into a confusing permission error (PLAN 13.1, C3).
mode_4755=$(stat -c '%a' "$work/usr/bin/darling" 2>/dev/null || echo missing)
[ "$mode_4755" = 4755 ] || fatal "$work/usr/bin/darling is mode $mode_4755, expected 4755: the .deb would ship a non-setuid runtime"

install -D -m 0644 packaging/deb/darling-lol.lintian-overrides \
  "$work/usr/share/lintian/overrides/darling-lol"
sh packaging/deb/mk-copyright.sh --upstream "$upstream_copyright" --if-missing "$copyright_missing" \
  --out "$pkg/copyright"
install -D -m 0644 "$pkg/copyright" "$work/usr/share/doc/darling-lol/copyright"

# --- 4. the launcher tree ----------------------------------------------------------------------
lwork=$pkg/deb-launcher
build_tree "$lwork" files.runtime files.launcher
install -D -m 0644 packaging/deb/darling-lol-launcher.lintian-overrides \
  "$lwork/usr/share/lintian/overrides/darling-lol-launcher"
install -D -m 0644 "$pkg/copyright" "$lwork/usr/share/doc/darling-lol-launcher/copyright"

# The launcher package owns templates and a wrapper and has NO maintainer scripts at all
# (TASKS.md T3): nothing in it needs a configure/remove step, and a postinst would only be a
# fifth place to get the SDK path wrong.
if [ -e "$lwork/DEBIAN" ]; then fatal "$lwork/DEBIAN already exists: the launcher package must have no maintainer scripts"; fi

# --- 5. the changelog --------------------------------------------------------------------------
# PLAN 9.5's changelog.in carries three placeholders render.sh does not know (@UPSTREAM_SHORT@,
# @COMMIT_SHORT@, @DATE_RFC2822@) -- render.sh's token table is fixed (T1, frozen). They are
# filled here, into a private copy of the template, and render.sh then fills @VERSION@ and
# @MAINTAINER@: its "refuse to emit an unexpanded token" guard is what proves the split worked, so
# a typo in a token name cannot reach the package. English day/month names and a numeric zone are
# policy requirements for a Debian changelog date, so the locale is pinned.
date_rfc2822=$(LC_ALL=C date -u '+%a, %d %b %Y %H:%M:%S +0000')
upstream_short=$(sed -n 's/.*"revision": "\([0-9a-f]\{12\}\)\([0-9a-f]*\)".*/\1/p' upstream/manifest.json 2>/dev/null | head -n 1)
[ -n "$upstream_short" ] || upstream_short=unknown
commit_short=$(git rev-parse --short=12 HEAD 2>/dev/null || echo unknown)
changelog_tpl=$pkg/changelog.tpl
sed -e "s|@UPSTREAM_SHORT@|$upstream_short|g" \
    -e "s|@COMMIT_SHORT@|$commit_short|g" \
    -e "s|@DATE_RFC2822@|$date_rfc2822|g" packaging/deb/changelog.in > "$changelog_tpl"
render "$changelog_tpl" > "$pkg/changelog.Debian"
check_no_tokens "$pkg/changelog.Debian"
# gzipped, as lintian expects (C4: `E: no-changelog`). -9n: no name, no timestamp, so the build
# is reproducible byte-for-byte.
gzip -9n -c "$pkg/changelog.Debian" > "$pkg/changelog.Debian.gz"
install -D -m 0644 "$pkg/changelog.Debian.gz" "$work/usr/share/doc/darling-lol/changelog.Debian.gz"
install -D -m 0644 "$pkg/changelog.Debian.gz" "$lwork/usr/share/doc/darling-lol-launcher/changelog.Debian.gz"

# --- 6. measure, then render the control files -------------------------------------------------
# Installed-Size is per package, measured over the tree that package actually ships. stage.sh's
# installed-size-kib is the size of the WHOLE staging tree and cannot serve two control files
# (PLAN 9.7's excerpt reads it for the runtime; PLAN 9.2 needs a launcher number that nothing
# generates). Both numbers are du -sk, the same unit stage.sh uses.
runtime_size=$(du -sk "$work" | awk '{print $1}')
launcher_size=$(du -sk "$lwork" | awk '{print $1}')

mkdir -p "$work/DEBIAN"
render packaging/deb/control.in --installed-size "$runtime_size" > "$work/DEBIAN/control"
render packaging/deb/postinst > "$work/DEBIAN/postinst"
render packaging/deb/postrm > "$work/DEBIAN/postrm"
render packaging/deb/prerm > "$work/DEBIAN/prerm"
chmod 0755 "$work/DEBIAN/postinst" "$work/DEBIAN/postrm" "$work/DEBIAN/prerm"
for f in control postinst postrm prerm; do check_no_tokens "$work/DEBIAN/$f"; done

mkdir -p "$lwork/DEBIAN"
render packaging/deb/launcher-control.in --launcher-installed-size "$launcher_size" > "$lwork/DEBIAN/control"
check_no_tokens "$lwork/DEBIAN/control"

# PLAN 9.3, C5/C7: no DEBIAN/conffiles. private/etc/resolv.conf is a plain 0644 data file: it
# lives in the overlayfs LOWERDIR, so the runtime never writes it, and registering it would be two
# lintian errors for nothing.
if [ -e "$work/DEBIAN/conffiles" ]; then fatal "$work/DEBIAN/conffiles exists: PLAN 9.3 forbids it (C5/C7)"; fi

# The artifact name and the metadata must not be able to disagree: the version in the file name
# comes from the rendered control file, not from a second derivation.
ctl_ver=$(sed -n 's/^Version: //p' "$work/DEBIAN/control")
[ "$ctl_ver" = "$ver" ] || fatal "$work/DEBIAN/control says Version $ctl_ver but pkg-version.sh --deb $tag says $ver"
lctl_dep=$(sed -n 's/^Depends: //p' "$lwork/DEBIAN/control")
case "$lctl_dep" in
  "darling-lol (= $ver), "*) : ;;
  *) fatal "the launcher's Depends does not pin darling-lol (= $ver): '$lctl_dep' (\${binary:Version} not substituted by render.sh?)" ;;
esac
if [ -z "$runtime_deb" ]; then
  runtime_deb=$dist/darling-lol_${ctl_ver}_${arch}.deb
  launcher_deb=$dist/darling-lol-launcher_${ctl_ver}_all.deb
fi

# --- 7. build ----------------------------------------------------------------------------------
rm -f "$runtime_deb" "$launcher_deb"
dpkg-deb --build --root-owner-group -Zxz "$work" "$runtime_deb"
dpkg-deb --build --root-owner-group -Zxz "$lwork" "$launcher_deb"

note "built $runtime_deb ($(wc -c < "$runtime_deb") bytes, Installed-Size $runtime_size KiB)"
note "built $launcher_deb ($(wc -c < "$launcher_deb") bytes, Installed-Size $launcher_size KiB)"
note "version $ctl_ver, family $deb_family, tag $tag"
